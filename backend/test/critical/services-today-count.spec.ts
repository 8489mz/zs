/*
New file: backend/test/critical/services-today-count.spec.ts
Pins the "خدمات اليوم" count staying 0 (INV-SERVICES-TODAY-COUNT).

THE GAP: listServices compared String(row.serviceDate).slice(0, 10) with
today = new Date().toISOString().slice(0, 10). service_date is TIMESTAMPTZ,
which pg returns as a JS Date, so String(date) is "Wed Nov 05 2026 ..." and
slice(0, 10) is "Wed Nov 05" -- never equal to "2026-11-05". todayCount was
therefore always 0, and the filter === 'today' slice (same comparison)
always returned []. A second, smaller defect rode along: today itself was
UTC, so a service recorded 00:00-02:00 Cairo (23:00-01:00 UTC) fell on the
previous UTC day and would not have counted even with a correct comparison.

THE RULE: "today" is the tenant-local day (getTenantTimezone +
todayTenantDate), and a row counts when its service_date falls on that
tenant-local day -- the row value is formatted in the tenant timezone,
never string-sliced as a JS Date and never compared in UTC.

WHAT THIS PINS, driving the REAL ServicesService.listServices on PGlite
(service_date is a real TIMESTAMPTZ column, so pg returns it as a JS Date
exactly as in production; the settings table seeds timezone Africa/Cairo
so the real tenant-timezone lookup path is exercised):
- a service at 01:00 Cairo today (23:00 UTC yesterday) counts as today.
- a service at 12:00 Cairo today counts as today.
- a service at 12:00 Cairo yesterday does NOT count.
- summary.todayCount is 2, and filter 'today' returns exactly the two
  today rows; filter 'all' still lists all three.
*/

import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely, sql } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { Database } from '../../src/database/database.types';
import { AuthContext } from '../../src/core/auth/interfaces/auth-context.interface';
import { ServicesService } from '../../src/modules/services/services.service';

const AUTH = { tenantId: 't1', accountId: 'a1', role: 'admin', userId: 1, username: 'admin', permissions: [] } as unknown as AuthContext;
const TZ = 'Africa/Cairo';

function cairoDay(date: Date): string {
  return new Intl.DateTimeFormat('en-CA', { timeZone: TZ }).format(date);
}

async function createDb(): Promise<Kysely<Database>> {
  const pglite = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pglite) });
  // Production DDL: phase2 foundation columns for services/branches/
  // stock_locations/users/settings plus the tenant_id / branch_id /
  // location_id / payment_channel columns later migrations added and
  // listServices reads. service_date stays TIMESTAMPTZ on purpose.
  await sql`
    CREATE TABLE branches (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL,
      name TEXT NOT NULL,
      code TEXT NOT NULL DEFAULT '',
      is_active BOOLEAN NOT NULL DEFAULT TRUE
    )
  `.execute(db);
  await sql`
    CREATE TABLE stock_locations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL,
      branch_id BIGINT NULL REFERENCES branches(id) ON DELETE SET NULL,
      name TEXT NOT NULL,
      code TEXT NOT NULL DEFAULT '',
      is_active BOOLEAN NOT NULL DEFAULT TRUE
    )
  `.execute(db);
  await sql`
    CREATE TABLE users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL,
      username TEXT NOT NULL,
      password_hash TEXT NOT NULL DEFAULT '',
      password_salt TEXT NOT NULL DEFAULT '',
      role TEXT NOT NULL DEFAULT 'admin',
      is_active BOOLEAN NOT NULL DEFAULT TRUE
    )
  `.execute(db);
  await sql`
    CREATE TABLE settings (
      tenant_id TEXT NOT NULL,
      key TEXT NOT NULL,
      value TEXT NOT NULL,
      PRIMARY KEY (tenant_id, key)
    )
  `.execute(db);
  await sql`
    CREATE TABLE services (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL,
      name TEXT NOT NULL,
      amount NUMERIC(14,2) NOT NULL DEFAULT 0,
      notes TEXT NOT NULL DEFAULT '',
      service_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      payment_channel TEXT NOT NULL DEFAULT 'cash',
      branch_id BIGINT NULL REFERENCES branches(id),
      location_id BIGINT NULL REFERENCES stock_locations(id),
      is_active BOOLEAN NOT NULL DEFAULT TRUE,
      created_by BIGINT NULL REFERENCES users(id),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `.execute(db);
  return db;
}

async function main(): Promise<void> {
  const db = await createDb();
  try {
    await sql`INSERT INTO settings (tenant_id, key, value) VALUES ('t1', 'timezone', 'Africa/Cairo')`.execute(db);
    await sql`INSERT INTO branches (id, tenant_id, name) VALUES (1, 't1', 'Main')`.execute(db);
    await sql`INSERT INTO stock_locations (id, tenant_id, branch_id, name) VALUES (1, 't1', 1, 'Store')`.execute(db);
    await sql`INSERT INTO users (id, tenant_id, username) VALUES (1, 't1', 'admin')`.execute(db);

    const today = cairoDay(new Date());
    const yesterday = cairoDay(new Date(Date.now() - 24 * 60 * 60 * 1000));
    // 01:00 Cairo today is 23:00 UTC yesterday: tenant-local today, UTC yesterday.
    const earlyToday = new Date(`${today}T01:00:00+02:00`);
    const noonToday = new Date(`${today}T12:00:00+02:00`);
    const noonYesterday = new Date(`${yesterday}T12:00:00+02:00`);
    // Sanity: the early row really is a different UTC day from today.
    assert.notEqual(earlyToday.toISOString().slice(0, 10), today);

    await sql`INSERT INTO services (tenant_id, name, amount, service_date, branch_id, location_id, created_by) VALUES ('t1', 'early today', 100, ${earlyToday}, 1, 1, 1)`.execute(db);
    await sql`INSERT INTO services (tenant_id, name, amount, service_date, branch_id, location_id, created_by) VALUES ('t1', 'noon today', 200, ${noonToday}, 1, 1, 1)`.execute(db);
    await sql`INSERT INTO services (tenant_id, name, amount, service_date, branch_id, location_id, created_by) VALUES ('t1', 'yesterday', 300, ${noonYesterday}, 1, 1, 1)`.execute(db);

    const service = new ServicesService(db as never, {} as never, {} as never, {} as never, {} as never);

    const all = (await service.listServices({}, AUTH)) as {
      services: Array<{ name: string }>;
      summary: { totalItems: number; todayCount: number };
    };
    assert.equal(all.summary.totalItems, 3, 'all three rows listed');
    assert.equal(all.summary.todayCount, 2, 'both Cairo-today rows count, yesterday does not');

    const todayOnly = (await service.listServices({ filter: 'today' }, AUTH)) as {
      services: Array<{ name: string }>;
      summary: { totalItems: number; todayCount: number };
    };
    assert.deepEqual(
      todayOnly.services.map((row) => row.name).sort(),
      ['early today', 'noon today'],
    );
    assert.equal(todayOnly.summary.todayCount, 2);

    console.log('services today count checks passed');
  } finally {
    await db.destroy();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
