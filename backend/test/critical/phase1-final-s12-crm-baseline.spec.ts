import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { BadRequestException, NotFoundException } from '@nestjs/common';
import { Database } from '../../src/database/database.types';
import { AuthContext } from '../../src/core/auth/interfaces/auth-context.interface';
import { CrmService } from '../../src/modules/crm/crm.service';

/*
 * Phase 1 final-inspection slice 12 — baseline spec for the crm
 * module (one of the 10 modules with zero primary specs on 95858d5).
 *
 * GROUNDING (live code, read before writing):
 * - CrmService (crm/crm.service.ts): Kysely only, no external
 *   calls. createDeal requires a title and a close date
 *   (INV-CRM-ERROR: the date is required, the error names the field
 *   in Arabic) and writes an initial 'note' timeline activity;
 *   updateDeal logs a 'stage_change' activity when the stage moves;
 *   deleteDeal removes the deal and its activities in one
 *   transaction; toggleActivity flips is_completed; convertToCustomer
 *   reuses a customer with the same phone, otherwise creates one,
 *   marks the deal won at probability 100 and logs a 'converted'
 *   activity; getPipelineSummary totals by stage with a probability-
 *   weighted active amount and a win rate.
 * - DDL for crm_deals / crm_activities is copied from
 *   crm-close-date-required.spec.ts (already linked); users +
 *   customers are minimal harness tables for the list/get joins and
 *   the conversion insert.
 *
 * WHAT THIS PROVES (real service on PGlite):
 * - Deal lifecycle: create defaults (stage new, probability 50,
 *   EGP), title + close-date required, get/list round-trip, tenant
 *   isolation, stage-change activity on update, missing-deal 404,
 *   delete removes the deal and its activities.
 * - Pipeline summary: counts, active vs won vs lost, weighted
 *   amount, win rate.
 * - Activities: add + toggle + missing-deal/activity 404.
 * - Conversion: new customer created from the contact, deal marked
 *   won, 'converted' activity logged, second conversion reuses the
 *   same customer by phone.
 *
 * NOT RUN: DTO/controller validation (stage/probability ranges are
 * enforced there, not in the service), UI, live Postgres.
 */

const DDL = `
  CREATE TABLE crm_deals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL DEFAULT '',
    title TEXT NOT NULL,
    stage TEXT NOT NULL DEFAULT 'new',
    expected_amount NUMERIC(15, 4) NOT NULL DEFAULT 0,
    currency TEXT NOT NULL DEFAULT 'EGP',
    probability INTEGER NOT NULL DEFAULT 50,
    expected_close_date DATE NULL,
    contact_name TEXT NULL,
    contact_phone TEXT NULL,
    contact_email TEXT NULL,
    company_name TEXT NULL,
    source TEXT NOT NULL DEFAULT 'direct',
    priority TEXT NOT NULL DEFAULT 'medium',
    assigned_user_id BIGINT NULL,
    customer_id BIGINT NULL,
    lost_reason TEXT NULL,
    notes TEXT NULL,
    created_by BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE crm_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL DEFAULT '',
    deal_id BIGINT NOT NULL,
    activity_type TEXT NOT NULL DEFAULT 'note',
    summary TEXT NOT NULL,
    due_date TIMESTAMPTZ NULL,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE users (
    id BIGINT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    username TEXT NOT NULL
  );
  CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    account_id TEXT,
    name TEXT NOT NULL,
    phone TEXT NOT NULL DEFAULT '',
    company_name TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    balance NUMERIC(15, 4) NOT NULL DEFAULT 0,
    customer_type TEXT NOT NULL DEFAULT 'cash',
    credit_limit NUMERIC(15, 4) NOT NULL DEFAULT 0,
    store_credit_balance NUMERIC(15, 4) NOT NULL DEFAULT 0,
    tax_number TEXT NOT NULL DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
`;

const auth = {
  tenantId: 't1',
  accountId: 'a1',
  userId: 1,
  username: 'admin',
  role: 'admin',
  permissions: ['crm'],
} as unknown as AuthContext;
const otherTenantAuth = {
  tenantId: 't2',
  accountId: 'a2',
  userId: 9,
  username: 'owner',
  role: 'admin',
  permissions: ['crm'],
} as unknown as AuthContext;

async function makeDb(): Promise<{ pg: PGlite; db: Kysely<Database> }> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  await pg.exec(DDL);
  await pg.query(`INSERT INTO users (id, tenant_id, username) VALUES (1, 't1', 'admin')`);
  return { pg, db };
}

async function expectError(promise: Promise<unknown>, cls: new (...args: never[]) => Error): Promise<Error> {
  try {
    await promise;
  } catch (error) {
    assert.ok(error instanceof cls, `expected ${cls.name}, got ${String(error)}`);
    return error as Error;
  }
  assert.fail(`expected ${cls.name}, but the call succeeded`);
  throw new Error('unreachable');
}

async function main(): Promise<void> {
  // ---- Part A: deal lifecycle ----
  {
    const { pg, db } = await makeDb();
    try {
      const crm = new CrmService(db);

      const noTitle = await expectError(
        crm.createDeal({ title: '  ', expectedCloseDate: '2026-12-01' } as never, auth),
        BadRequestException,
      );
      assert.ok(noTitle.message.includes('عنوان'), 'the empty-title error names the title');
      const noDate = await expectError(crm.createDeal({ title: 'توريد معدات' } as never, auth), BadRequestException);
      assert.ok(noDate.message.includes('تاريخ الإغلاق'), 'the missing-date error names the close date');

      const created = await crm.createDeal(
        {
          title: 'توريد معدات',
          expectedCloseDate: '2026-12-01',
          expectedAmount: 10000,
          probability: 60,
          contactName: 'أحمد محمد',
          contactPhone: '01012345678',
          companyName: 'شركة النور',
        } as never,
        auth,
      );
      assert.equal(created.ok, true, 'creating a deal succeeds');
      const dealId = Number(created.deal.id);
      assert.equal(created.deal.stage, 'new', 'a new deal starts at stage new');
      assert.equal(Number(created.deal.probability), 60, 'the given probability is stored');
      assert.equal(created.deal.currency, 'EGP', 'the currency defaults to EGP');

      const fetched = await crm.getDeal(dealId, auth);
      assert.equal(fetched.deal.title, 'توريد معدات', 'get returns the deal');
      assert.equal(fetched.activities.length, 1, 'creation writes one timeline activity');
      assert.equal(
        (fetched.activities as unknown as Array<{ activityType: string }>)[0].activityType,
        'note',
        'the creation activity is a note',
      );

      const listed = await crm.listDeals({}, auth);
      assert.equal(listed.deals.length, 1, 'one deal is listed');
      assert.equal(listed.deals[0].contactName, 'أحمد محمد', 'the list carries the contact name');
      assert.equal((await crm.listDeals({}, otherTenantAuth)).deals.length, 0, 'deals are tenant-scoped');
      assert.equal(
        (await crm.listDeals({ stage: 'won' }, auth)).deals.length,
        0,
        'the stage filter excludes new deals',
      );
      await expectError(crm.getDeal(dealId, otherTenantAuth), NotFoundException);
      await expectError(crm.getDeal(999999, auth), NotFoundException);

      const updated = await crm.updateDeal(dealId, { stage: 'negotiation', expectedAmount: 12000 } as never, auth);
      assert.equal(updated.deal.stage, 'negotiation', 'the stage updates');
      assert.equal(Number(updated.deal.expected_amount), 12000, 'the amount updates');
      const afterStage = await crm.getDeal(dealId, auth);
      assert.equal(afterStage.activities.length, 2, 'the stage change logs an activity');
      assert.equal(
        (afterStage.activities as unknown as Array<{ activityType: string }>)[0].activityType,
        'stage_change',
        'the newest activity is the stage change',
      );
      await expectError(crm.updateDeal(999999, { stage: 'won' } as never, auth), NotFoundException);

      const deleted = await crm.deleteDeal(dealId, auth);
      assert.equal(deleted.ok, true, 'deleting succeeds');
      assert.equal((await crm.listDeals({}, auth)).deals.length, 0, 'no deals remain');
      const activitiesLeft = await pg.query<{ n: string }>(`SELECT COUNT(*) AS n FROM crm_activities`);
      assert.equal(Number(activitiesLeft.rows[0].n), 0, 'the deal activities are deleted with it');
      await expectError(crm.deleteDeal(dealId, auth), NotFoundException);
    } finally {
      await db.destroy();
    }
    console.log('  deal lifecycle passed');
  }

  // ---- Part B: pipeline summary ----
  {
    const { db } = await makeDb();
    try {
      const crm = new CrmService(db);
      await crm.createDeal(
        { title: 'صفقة أ', expectedCloseDate: '2026-12-01', expectedAmount: 10000, probability: 50 } as never,
        auth,
      );
      await crm.createDeal(
        {
          title: 'صفقة ب',
          expectedCloseDate: '2026-12-01',
          expectedAmount: 20000,
          probability: 80,
          stage: 'proposal',
        } as never,
        auth,
      );
      const won = await crm.createDeal(
        { title: 'صفقة ج', expectedCloseDate: '2026-12-01', expectedAmount: 5000, probability: 100 } as never,
        auth,
      );
      await crm.updateDeal(Number(won.deal.id), { stage: 'won' } as never, auth);
      const lost = await crm.createDeal(
        { title: 'صفقة د', expectedCloseDate: '2026-12-01', expectedAmount: 3000, probability: 0 } as never,
        auth,
      );
      await crm.updateDeal(Number(lost.deal.id), { stage: 'lost' } as never, auth);

      const summary = await crm.getPipelineSummary(auth);
      assert.equal(summary.summary.totalDeals, 4, 'four deals in total');
      assert.equal(summary.summary.totalActiveCount, 2, 'two deals are still active');
      assert.equal(summary.summary.totalActiveAmount, 30000, 'the active amount sums the two open deals');
      assert.equal(summary.summary.weightedAmount, 21000, 'the weighted amount is 10000*50% + 20000*80%');
      assert.equal(summary.summary.wonCount, 1, 'one deal is won');
      assert.equal(summary.summary.wonAmount, 5000, 'the won amount is 5000');
      assert.equal(summary.summary.lostCount, 1, 'one deal is lost');
      assert.equal(summary.summary.winRate, 50, 'the win rate is 1 of 2 closed');
      assert.equal(summary.summary.stageBreakdown.new.count, 1, 'one deal is new');
      assert.equal(summary.summary.stageBreakdown.proposal.totalAmount, 20000, 'the proposal stage totals 20000');
    } finally {
      await db.destroy();
    }
    console.log('  pipeline summary passed');
  }

  // ---- Part C: activities + conversion ----
  {
    const { pg, db } = await makeDb();
    try {
      const crm = new CrmService(db);
      const created = await crm.createDeal(
        {
          title: 'توريد أثاث',
          expectedCloseDate: '2026-12-15',
          expectedAmount: 8000,
          contactName: 'منى علي',
          contactPhone: '01122223333',
          companyName: 'مفروشات منى',
        } as never,
        auth,
      );
      const dealId = Number(created.deal.id);

      await expectError(crm.addActivity(999999, { summary: 'x' } as never, auth), NotFoundException);
      const added = await crm.addActivity(
        dealId,
        { activityType: 'call', summary: 'اتصال أولي مع العميلة', dueDate: '2026-11-30T10:00:00Z' } as never,
        auth,
      );
      assert.equal(added.activity.activity_type, 'call', 'the activity type is stored');
      assert.equal(added.activity.isCompleted, false, 'a new activity starts incomplete');
      const toggled = await crm.toggleActivity(Number(added.activity.id), auth);
      assert.equal(toggled.activity.isCompleted, true, 'toggling completes the activity');
      const toggledBack = await crm.toggleActivity(Number(added.activity.id), auth);
      assert.equal(toggledBack.activity.isCompleted, false, 'toggling again reopens it');
      await expectError(crm.toggleActivity(999999, auth), NotFoundException);

      const converted = await crm.convertToCustomer(dealId, auth);
      assert.equal(converted.ok, true, 'conversion succeeds');
      assert.ok(converted.customerId, 'a customer id is returned');
      const customer = await pg.query<{ name: string; phone: string; company_name: string }>(
        `SELECT name, phone, company_name FROM customers WHERE id=$1`,
        [converted.customerId],
      );
      assert.equal(customer.rows[0].name, 'منى علي', 'the customer takes the contact name');
      assert.equal(customer.rows[0].phone, '01122223333', 'the customer keeps the phone');
      assert.equal(customer.rows[0].company_name, 'مفروشات منى', 'the customer keeps the company');
      const dealAfter = await crm.getDeal(dealId, auth);
      assert.equal(dealAfter.deal.stage, 'won', 'the deal is marked won');
      assert.equal(Number(dealAfter.deal.probability), 100, 'the deal probability is 100');
      assert.equal(Number(dealAfter.deal.customer_id), Number(converted.customerId), 'the deal links the customer');
      assert.ok(
        (dealAfter.activities as unknown as Array<{ activityType: string }>).some(
          (a) => a.activityType === 'converted',
        ),
        'a converted activity is logged',
      );

      const convertedAgain = await crm.convertToCustomer(dealId, auth);
      assert.equal(
        Number(convertedAgain.customerId),
        Number(converted.customerId),
        'converting again reuses the same customer',
      );
      const customerCount = await pg.query<{ n: string }>(`SELECT COUNT(*) AS n FROM customers`);
      assert.equal(Number(customerCount.rows[0].n), 1, 'no second customer is created');
      await expectError(crm.convertToCustomer(999999, auth), NotFoundException);
    } finally {
      await db.destroy();
    }
    console.log('  activities + conversion passed');
  }

  console.log('phase1 final slice 12 crm baseline passed');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
