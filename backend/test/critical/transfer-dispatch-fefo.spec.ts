/*
New file: backend/test/critical/transfer-dispatch-fefo.spec.ts

WHAT THIS PINS (INV-TRANSFER-DISPATCH-FEFO):
dispatchTrackedStock allocates batch-tracked stock
first-expiry-first-out, skipping expired and non-active
lots -- the sale path's FEFO rule, shared verbatim. Before
this fix dispatch ordered candidates by id ascending with
no status or expiry filter, so a transfer shipped the
oldest-created lots first, including expired ones, while
the destination branch would then refuse to sell them.

THE RULE, COPIED FROM deductPharmacyBatchesFefo AT SALE
TIME: only 'active' batches; a 7-char expiry (YYYY-MM)
must not precede the current month; a full date must not
precede today; a missing expiry never dispatches. Explicit
batchAllocations are held to the same rule: naming an
expired batch must not bypass it.

THE CASES, WORKED ONCE (dates are relative to today, so
the spec does not rot):
(a) FEFO ORDER: batches B1 (expired yesterday, 5),
B2 (expires in 60 days, 5), B3 (expires in 10 days, 5);
dispatch 6 with no explicit allocation takes B3 5 then
B2 1; B1 is untouched.
(b) EXPLICIT BYPASS BLOCKED: naming the expired B1
explicitly throws TRANSFER_BATCH_NOT_AVAILABLE and moves
nothing.
(c) ONLY EXPIRED STOCK: dispatching 2 when every lot is
expired throws TRANSFER_BATCH_ALLOCATION_REQUIRED.
(d) MISSING EXPIRY: a lot with no expiry is skipped, the
same as at sale time; with no other lot the dispatch
throws TRANSFER_BATCH_ALLOCATION_REQUIRED.

HOW THIS IS DRIVEN: dispatchTrackedStock itself, in a
transaction over PGlite. Quantities are read from the
batch rows after the call, never re-implemented.

RED PROOF: on the unfixed tree case (a) takes B1 5 then
B2 1 -- the expired lot ships first.
*/

import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { Database } from '../../src/database/database.types';
import { dispatchTrackedStock } from '../../src/modules/inventory/helpers/stock-transfer-trace.helper';

const TENANT = 't1';
const ACCOUNT = 'a1';
const PRODUCT = 10;

function isoDays(offset: number): string {
  const d = new Date(Date.now() + offset * 86400000);
  return d.toISOString().slice(0, 10);
}

async function makeDb(): Promise<{ pg: PGlite; db: Kysely<Database> }> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  await pg.exec(`
    CREATE TABLE products (id bigint PRIMARY KEY, tenant_id text, track_serials boolean DEFAULT false);
    CREATE TABLE product_serials (id bigserial PRIMARY KEY, tenant_id text, product_id bigint, serial_number text, imei_2 text, status text, location_id bigint, branch_id bigint, updated_at timestamptz DEFAULT NOW());
    CREATE TABLE pharmacy_drugs (id bigserial PRIMARY KEY, tenant_id text, product_id bigint);
    CREATE TABLE pharmacy_batches (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id text, account_id text, product_id bigint, drug_id bigint, batch_number text, expiry_date text, quantity numeric, unit_cost numeric, location_id bigint, supplier_name text, status text, notes text, updated_at timestamptz DEFAULT NOW());
  `);
  const anyDb = db as any;
  await anyDb.insertInto('products').values({ id: PRODUCT, tenant_id: TENANT, track_serials: false }).execute();
  await anyDb.insertInto('pharmacy_drugs').values({ id: 1, tenant_id: TENANT, product_id: PRODUCT }).execute();
  return { pg, db };
}

async function seedBatch(db: Kysely<Database>, id: number, expiry: string, qty: number, status = 'active'): Promise<void> {
  await (db as any).insertInto('pharmacy_batches').values({
    id, tenant_id: TENANT, account_id: ACCOUNT, product_id: PRODUCT, drug_id: 1,
    batch_number: `B${id}`, expiry_date: expiry, quantity: qty, unit_cost: 10,
    location_id: 1, supplier_name: 'supplier', status,
  }).execute();
}

async function batchQty(db: Kysely<Database>, id: number): Promise<number> {
  const row = await (db as any).selectFrom('pharmacy_batches').select('quantity').where('id', '=', id).executeTakeFirst();
  return Number(row?.quantity || 0);
}

async function dispatch(db: Kysely<Database>, qty: number, batchAllocations?: Array<{ batchId: number; qty: number }>): Promise<any> {
  return db.transaction().execute(async (trx) => dispatchTrackedStock(
    trx as any, { tenantId: TENANT, accountId: ACCOUNT },
    { productId: PRODUCT, qty, batchAllocations }, 1, null, 2, 99,
  ));
}

async function expectThrow(fn: () => Promise<unknown>, codeFragment: string): Promise<void> {
  let thrown: any = null;
  try {
    await fn();
  } catch (err: any) {
    thrown = err;
  }
  assert.ok(thrown, `expected a throw containing: ${codeFragment}`);
  assert.match(String(thrown?.code || thrown?.message || ''), new RegExp(codeFragment), 'the error names the failure');
}

async function main(): Promise<void> {
  // (a) FEFO order: soonest-expiring first, expired skipped.
  {
    const { pg, db } = await makeDb();
    try {
      await seedBatch(db, 101, isoDays(-1), 5); // expired yesterday
      await seedBatch(db, 102, isoDays(60), 5);
      await seedBatch(db, 103, isoDays(10), 5);
      const result = await dispatch(db, 6);
      const bySource = new Map(result.batchTracking.map((row: any) => [row.sourceBatchId, row.qty]));
      assert.equal(bySource.get(103), 5, 'the soonest-expiring lot ships first');
      assert.equal(bySource.get(102), 1, 'the remainder comes from the later lot');
      assert.equal(bySource.has(101), false, 'the expired lot never ships');
      assert.equal(await batchQty(db, 101), 5, 'the expired lot keeps its full quantity');
      assert.equal(await batchQty(db, 103), 0, 'the soonest lot is fully consumed');
      assert.equal(await batchQty(db, 102), 4, 'the later lot keeps the remainder');
    } finally {
      await db.destroy();
    }
    console.log('  Transfer dispatch FEFO order passed');
  }

  // (b) Explicit allocation of the expired lot is blocked.
  {
    const { pg, db } = await makeDb();
    try {
      await seedBatch(db, 101, isoDays(-1), 5);
      await seedBatch(db, 102, isoDays(60), 5);
      await expectThrow(() => dispatch(db, 2, [{ batchId: 101, qty: 2 }]), 'TRANSFER_BATCH_NOT_AVAILABLE');
      assert.equal(await batchQty(db, 101), 5, 'the expired lot is untouched');
      assert.equal(await batchQty(db, 102), 5, 'no other lot moves either');
    } finally {
      await db.destroy();
    }
    console.log('  Explicit expired allocation blocked passed');
  }

  // (c) Only expired stock: nothing dispatchable.
  {
    const { pg, db } = await makeDb();
    try {
      await seedBatch(db, 101, isoDays(-30), 5);
      await expectThrow(() => dispatch(db, 2), 'TRANSFER_BATCH_ALLOCATION_REQUIRED');
      assert.equal(await batchQty(db, 101), 5, 'the expired lot is untouched');
    } finally {
      await db.destroy();
    }
    console.log('  Only-expired dispatch rejection passed');
  }

  // (d) A lot with no expiry is skipped like at sale time.
  {
    const { pg, db } = await makeDb();
    try {
      await seedBatch(db, 101, '', 5);
      await expectThrow(() => dispatch(db, 2), 'TRANSFER_BATCH_ALLOCATION_REQUIRED');
      assert.equal(await batchQty(db, 101), 5, 'the no-expiry lot is untouched');
    } finally {
      await db.destroy();
    }
    console.log('  Missing-expiry skip passed');
  }

  console.log('Transfer dispatch FEFO tests passed');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
