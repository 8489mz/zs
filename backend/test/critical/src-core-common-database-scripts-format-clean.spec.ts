/*
 * L6 scoped guard: src/core + src/common + src/database
 * (non-migration) + src top-level/config/tools + backend/scripts
 * must stay Prettier-clean under the repo config
 * (backend/.prettierrc: singleQuote, printWidth 120), EXCEPT any
 * files named in EXCLUDED below that are deliberately left
 * unformatted. The scope holds 143 files; 92 failed
 * `prettier --check` at the L5b base (44937e7fd, re-counted at fix
 * time — core 37 + common 19 = 56, database non-migration 10,
 * src top-level 2 + config 3 + tools 1 = 6, scripts 20) and L6
 * formats 89 of them with a pure `prettier --write`.
 *
 * STOPPED — database.types.ts (GENERATED, not a size-cap case):
 * `src/database/database.types.ts` (6489 lines) is generated by
 * kysely-codegen (package.json has the tool;
 * check-architecture-guardrails.cjs lists it as GENERATED) and
 * allowlisted from the file-size cap (never counted, not
 * baselined). Formatting it would grow it 6489 -> 6667 (measured
 * via prettier stdout, no modification) — pure churn the next
 * kysely-codegen run would undo, re-breaking this guard. It is
 * never --write'd and pinned below as an excluded file.
 *
 * STOPPED — size-cap collision, L4 way (2 files): `prettier
 * --write` grows these past the file-size cap purely by breaking
 * their long lines — session.service.ts 1023 -> 1294 (longest HEAD
 * line 417 chars; baselined 1023, so the guard trips) and
 * location-stock-ledger.ts 969 -> 1074 (longest HEAD line 199
 * chars; unbaselined, so the 1000 cap trips). Both were reverted
 * to HEAD and pinned below. session.service.ts at 1294 stays
 * excluded (over the user's 1110 split cutoff); location-stock-
 * ledger.ts at 1074 lands at or below 1110 and could be formatted
 * + baselined under the L4b/L5b precedent — that decision belongs
 * to the parent (a possible L6b), so it is STOPPED here like the
 * other file. Full table in ~/workspace/audit/lint-prettier-log.md
 * L6.
 *
 * L8 deletes this spec when the global backend-format-clean guard
 * lands — the global guard inherits the same exclusion until the
 * 3 files are resolved.
 *
 * This spec invokes `npx prettier --check` on the scope globs so
 * the exact tool CI runs is what is asserted — in CI, `npm ci`
 * installs prettier (devDep, lock 3.10.1), so npx resolves the local
 * binary there; locally it uses the npx cache.
 *
 * Fail-first: on the pre-L6 tree this spec exits 1 (92 files fail,
 * not the 3); after L6 it exits 1 with exactly the 3 excluded
 * files failing. A second shape is proven by reverting one
 * formatted file (see the log): the spec goes red until it is
 * restored.
 */

import { strict as assert } from 'node:assert';
import { spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'path';

const BACKEND = path.resolve(__dirname, '../..');
const GLOBS = [
  'src/core/**/*.ts',
  'src/common/**/*.ts',
  'src/database/*.ts',
  'src/database/helpers/**/*.ts',
  'src/database/legacy-migration/**/*.ts',
  'src/*.ts',
  'src/config/**/*.ts',
  'src/tools/**/*.ts',
  'scripts/**/*.{cjs,mjs,js,ts}',
];

/** Files deliberately left unformatted (see header). */
const EXCLUDED: string[] = [
  'src/common/utils/location-stock-ledger.ts',
  'src/core/auth/services/session.service.ts',
  'src/database/database.types.ts',
];

function countTsRecursive(dir: string): number {
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      total += countTsRecursive(full);
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      total += 1;
    }
  }
  return total;
}

function countTopLevelTs(dir: string): number {
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith('.ts')) {
      total += 1;
    }
  }
  return total;
}

function countScripts(dir: string): number {
  const exts = new Set(['.cjs', '.mjs', '.js', '.ts']);
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      total += countScripts(full);
    } else if (entry.isFile() && exts.has(path.extname(entry.name))) {
      total += 1;
    }
  }
  return total;
}

function tail(text: string, lines: number): string {
  const parts = text.split('\n');
  return parts.slice(Math.max(0, parts.length - lines)).join('\n');
}

function main(): void {
  const total =
    countTsRecursive(path.join(BACKEND, 'src', 'core')) +
    countTsRecursive(path.join(BACKEND, 'src', 'common')) +
    countTopLevelTs(path.join(BACKEND, 'src', 'database')) +
    countTsRecursive(path.join(BACKEND, 'src', 'database', 'helpers')) +
    countTsRecursive(path.join(BACKEND, 'src', 'database', 'legacy-migration')) +
    countTopLevelTs(path.join(BACKEND, 'src')) +
    countTsRecursive(path.join(BACKEND, 'src', 'config')) +
    countTsRecursive(path.join(BACKEND, 'src', 'tools')) +
    countScripts(path.join(BACKEND, 'scripts'));
  assert.ok(total > 0, 'the L6 scope must contain files');
  const result = spawnSync('npx', ['prettier', '--check', ...GLOBS], {
    cwd: BACKEND,
    encoding: 'utf8',
    stdio: 'pipe',
    timeout: 5 * 60 * 1000,
    maxBuffer: 16 * 1024 * 1024,
  });
  const combined = `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
  const failing = combined
    .split('\n')
    .filter((line) => line.startsWith('[warn] '))
    .map((line) => line.slice('[warn] '.length).trim())
    .filter((line) => line.endsWith('.ts') || line.endsWith('.cjs') || line.endsWith('.mjs') || line.endsWith('.js'))
    .sort();
  const expected = [...EXCLUDED].sort();
  if (expected.length === 0) {
    assert.equal(
      result.status,
      0,
      `prettier --check on the L6 scope must exit 0 (no files fail). Got exit ${String(result.status)} signal ${String(result.signal)}.\n${tail(combined, 30)}`,
    );
    assert.deepEqual(
      failing,
      expected,
      `no files must fail prettier --check in the L6 scope.\nFailing: ${JSON.stringify(failing)}`,
    );
  } else {
    assert.equal(
      result.status,
      1,
      `prettier --check on the L6 scope must exit 1 (exactly the ${String(EXCLUDED.length)} excluded file(s) fail). Got exit ${String(result.status)} signal ${String(result.signal)}.\n${tail(combined, 30)}`,
    );
    assert.deepEqual(
      failing,
      expected,
      `the failing files must be exactly the ${String(EXCLUDED.length)} excluded file(s).\nFailing: ${JSON.stringify(failing)}\nExpected: ${JSON.stringify(expected)}`,
    );
  }
  console.log(`L6 scope format clean check passed (${total} files, ${EXCLUDED.length} excluded)`);
}

main();
