/*
New file: backend/test/critical/crm-close-date-required.spec.ts

WHAT THIS PINS (INV-CRM-ERROR): creating a sales opportunity without a
close date must fail with an error that names the close date
('تاريخ الإغلاق مطلوب.'), never the generic 'البيانات المدخلة غير صحيحة.'.

THE GAP (grounded at live HEAD cfd1eae):
- The create modal posts expectedCloseDate: '' when the user leaves the
  date empty (CrmDealCreateModal.tsx initial form), and its submit guard
  checked only the title.
- CreateDealDto had @IsOptional() @IsDateString() on the field, but
  @IsOptional() skips only null/undefined, NOT ''. So '' died in the
  global requestValidationPipe as a date-format error whose message the
  pipe rendered as 'الحقل expectedCloseDate يجب أن يكون تاريخًا صحيحًا.'
  (FIELD_LABELS has no expectedCloseDate entry, so the raw camelCase
  property leaked) -- and the frontend error mapper
  (getFriendlyApiErrorMessage) tries the VALIDATION_ERROR code mapping
  first, discarding that specific message for the generic
  'البيانات المدخلة غير صحيحة.'.
- A genuinely missing date (null/omitted) passed the pipe AND the
  service, which only validated the title and stored null -- no error
  at all, even though the close date is a required field.

THE FIX (CRM-scoped; the shared frontend mapper precedence is flagged
in the package report, not changed here):
- CreateDealDto normalises '' to undefined via @Transform, so the empty
  string reaches the service as "missing" instead of a format error.
- CrmService.createDeal rejects a missing close date with a plain
  BadRequestException('تاريخ الإغلاق مطلوب.') -- no VALIDATION_ERROR
  code, so the backend filter keeps the message and the frontend mapper
  falls through to it instead of the generic code text.
- The modal guards the submit (same pattern as the title guard) and
  marks the field required.

HOW THIS IS DRIVEN: the real CrmService.createDeal on PGlite, plus the
real global requestValidationPipe for the ''-normalisation cases (the
exact path the modal's payload travels). A valid date still creates the
deal and stores the date; the title check is unchanged.
*/

import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { BadRequestException } from '@nestjs/common';
import { Database } from '../../src/database/database.types';
import { AuthContext } from '../../src/core/auth/interfaces/auth-context.interface';
import { CrmService } from '../../src/modules/crm/crm.service';
import { CreateDealDto } from '../../src/modules/crm/dto/crm.dto';
import { requestValidationPipe } from '../../src/common/pipes/request-validation.pipe';

const TENANT = 't1';
const ACCOUNT = 'a1';

const auth: AuthContext = {
  userId: 1, sessionId: 'spec', username: 'admin', role: 'admin',
  permissions: ['crm'], tenantId: TENANT, accountId: ACCOUNT,
} as unknown as AuthContext;

async function makeDb(): Promise<{ pg: PGlite; db: Kysely<Database> }> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  await pg.exec(`
    CREATE TABLE crm_deals (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL DEFAULT '',
      title TEXT NOT NULL,
      stage TEXT NOT NULL DEFAULT 'new',
      expected_amount NUMERIC(15, 4) NOT NULL DEFAULT 0,
      currency TEXT NOT NULL DEFAULT 'EGP',
      probability INTEGER NOT NULL DEFAULT 50,
      expected_close_date DATE NULL,
      contact_name TEXT NULL,
      contact_phone TEXT NULL,
      contact_email TEXT NULL,
      company_name TEXT NULL,
      source TEXT NOT NULL DEFAULT 'direct',
      priority TEXT NOT NULL DEFAULT 'medium',
      assigned_user_id BIGINT NULL,
      customer_id BIGINT NULL,
      lost_reason TEXT NULL,
      notes TEXT NULL,
      created_by BIGINT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
    CREATE TABLE crm_activities (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id TEXT NOT NULL DEFAULT '',
      deal_id BIGINT NOT NULL,
      activity_type TEXT NOT NULL DEFAULT 'note',
      summary TEXT NOT NULL,
      due_date TIMESTAMPTZ NULL,
      is_completed BOOLEAN NOT NULL DEFAULT FALSE,
      created_by BIGINT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);
  return { pg, db };
}

function namesCloseDate(err: unknown): boolean {
  return Boolean(
    err &&
    typeof (err as { message?: unknown }).message === 'string' &&
    ((err as { message: string }).message.includes('تاريخ الإغلاق')),
  );
}

async function main(): Promise<void> {
  // 1. Missing close date: the error names the close date.
  {
    const { db } = await makeDb();
    try {
      const service = new CrmService(db);
      await assert.rejects(
        service.createDeal({ title: 'توريد معدات' } as any, auth),
        (err: unknown) =>
          err instanceof BadRequestException && namesCloseDate(err),
      );
    } finally {
      await db.destroy();
    }
    console.log('  missing close date names the field passed');
  }

  // 2. Empty-string close date (exactly what the modal posts when the
  // user leaves the date empty): same named error, not a format error.
  {
    const { db } = await makeDb();
    try {
      const service = new CrmService(db);
      await assert.rejects(
        service.createDeal({ title: 'توريد معدات', expectedCloseDate: '' } as any, auth),
        (err: unknown) =>
          err instanceof BadRequestException && namesCloseDate(err),
      );
    } finally {
      await db.destroy();
    }
    console.log('  empty-string close date names the field passed');
  }

  // 3. A valid close date still creates the deal and stores the date.
  {
    const { db } = await makeDb();
    try {
      const service = new CrmService(db);
      const result = await service.createDeal(
        { title: 'توريد معدات', expectedCloseDate: '2026-12-01' } as any,
        auth,
      );
      assert.equal(result.ok, true, 'the deal is created');
      assert.ok(Number(result.deal.id) > 0, 'the deal has an id');
      const row = await (db as any)
        .selectFrom('crm_deals')
        .select('expected_close_date')
        .where('id', '=', Number(result.deal.id))
        .executeTakeFirstOrThrow();
      const stored = new Date(row.expected_close_date as any);
      assert.equal(stored.getFullYear(), 2026, 'the stored year matches');
      assert.equal(stored.getMonth(), 11, 'the stored month matches');
      assert.equal(stored.getDate(), 1, 'the stored day matches');
      const activities = await (db as any)
        .selectFrom('crm_activities')
        .select('id')
        .where('deal_id', '=', Number(result.deal.id))
        .execute();
      assert.equal(activities.length, 1, 'the creation note is recorded');
    } finally {
      await db.destroy();
    }
    console.log('  valid close date creates the deal passed');
  }

  // 4. The title check is unchanged and still runs first.
  {
    const { db } = await makeDb();
    try {
      const service = new CrmService(db);
      await assert.rejects(
        service.createDeal({ title: '   ' } as any, auth),
        (err: unknown) =>
          err instanceof BadRequestException &&
          typeof (err as { message: string }).message === 'string' &&
          (err as { message: string }).message.includes('عنوان الفرصة البيعية مطلوب'),
      );
    } finally {
      await db.destroy();
    }
    console.log('  title check unchanged passed');
  }

  // 5. The live modal path: the real validation pipe normalises '' to
  // missing (no throw), and the service then rejects with the named
  // error -- the generic validation message never appears.
  {
    const { db } = await makeDb();
    try {
      const transformed = (await requestValidationPipe.transform(
        { title: 'توريد معدات', expectedCloseDate: '' },
        { type: 'body', metatype: CreateDealDto },
      )) as CreateDealDto;
      assert.equal(
        transformed.expectedCloseDate,
        undefined,
        "the pipe normalises the modal's empty string to missing",
      );
      const service = new CrmService(db);
      await assert.rejects(
        service.createDeal(transformed as any, auth),
        (err: unknown) =>
          err instanceof BadRequestException && namesCloseDate(err),
      );
    } finally {
      await db.destroy();
    }
    console.log('  pipe normalises empty string, service names the field passed');
  }

  // 6. The pipe still passes a valid date through unchanged.
  {
    const transformed = (await requestValidationPipe.transform(
      { title: 'توريد معدات', expectedCloseDate: '2026-12-01' },
      { type: 'body', metatype: CreateDealDto },
    )) as CreateDealDto;
    assert.equal(
      transformed.expectedCloseDate,
      '2026-12-01',
      'a valid close date survives the pipe',
    );
    console.log('  pipe passes a valid close date passed');
  }

  console.log('CRM close date required tests passed');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
