/*
New file: backend/test/critical/duplicate-phone-warn.spec.ts
Pins Batch 11 P5 (INV-DUPLICATE-PHONE-WARN): a customer phone that is
already registered to another customer in the same tenant warns but
still allows the save (user decision 2026-11-06 23:20: warn but allow).

WHAT THIS PINS, driving the REAL PartnersService on PGlite:
- Create customer A with phone P: ok, saved, NO warning.
- Create customer B (different name) with the same phone P: ok, B is
  saved under its own id, and the response carries phoneWarning
  naming A (name + phone).
- Update B's phone away from P and back to P: both saves allowed;
  the save back to P carries phoneWarning naming A.
- Create with a fresh phone: saved, no warning.
- Create with a digit-variant of P (+2010... for stored 010...):
  the warning still fires, via generatePhoneSearchVariants.

HONEST CAVEAT: there is no phone-duplicate rejection anywhere in
this codebase (no unique index on customers.phone, no check in
createCustomer/updateCustomer), so the save-allowed half of the
assertions already passes without the fix. The spec fails
without the fix ONLY on the phoneWarning assertions — that is the
correct proof for this package as scoped (purely additive warning).
*/

import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { Database } from '../../src/database/database.types';
import { AuthContext } from '../../src/core/auth/interfaces/auth-context.interface';
import { PartnersService } from '../../src/modules/partners/partners.service';

async function main(): Promise<void> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  try {
    await pg.exec(`
      CREATE TABLE settings (tenant_id text, key text, value text);
      CREATE TABLE currency_exchange_rates (tenant_id text, currency_code text, exchange_rate numeric, is_base boolean);
      CREATE TABLE customers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id text, account_id text, name text, phone text, address text, balance numeric DEFAULT 0, customer_type text, credit_limit numeric DEFAULT 0, store_credit_balance numeric DEFAULT 0, company_name text, tax_number text, metadata text, loyalty_points numeric DEFAULT 0, is_active boolean, created_at timestamptz, updated_at timestamptz);
      CREATE TABLE customer_ledger (customer_id bigint, entry_type text, amount numeric, balance_after numeric, note text, reference_type text, reference_id bigint, created_by bigint, branch_id bigint, location_id bigint, tenant_id text, account_id text, van_trip_id bigint);
      CREATE TABLE van_sales_trips (id bigint PRIMARY KEY, tenant_id text, rep_id bigint);
      CREATE TABLE sales (id bigint PRIMARY KEY, tenant_id text, delivery_rep_id bigint);
      CREATE TABLE van_field_returns (id bigint PRIMARY KEY, tenant_id text, rep_id bigint);
      CREATE TABLE delivery_representatives (id bigint PRIMARY KEY, tenant_id text, name text);
    `);
    await pg.exec(`
      INSERT INTO settings VALUES ('t1', 'currency', '"EGP"');
      INSERT INTO currency_exchange_rates VALUES ('t1', 'EGP', 1, true);
    `);

    const fakePosting: any = {
      postCustomerOpeningBalance: async () => {},
      postSupplierOpeningBalance: async () => {},
    };
    const svc: any = new PartnersService(db as any, { log: async () => {} } as any, fakePosting);
    const auth = { tenantId: 't1', accountId: 'a1', role: 'admin', userId: 1, permissions: [] } as unknown as AuthContext;

    const phone = '01012345678';

    // (1) First customer with phone P: saved, no warning.
    const createdA: any = await svc.createCustomer(
      { name: 'عميل أول', phone, address: '', balance: 0, type: 'cash', creditLimit: 0, storeCreditBalance: 0 },
      auth,
    );
    assert.equal(createdA.ok, true);
    assert.equal(createdA.phoneWarning, undefined);
    const idA = String(createdA.id);
    const rowA: any = await db.selectFrom('customers' as any).selectAll().where('id', '=', Number(idA)).executeTakeFirst();
    assert.equal(rowA.phone, phone);

    // (2) Second customer, different name, same phone: saved anyway, warned naming A.
    const createdB: any = await svc.createCustomer(
      { name: 'عميل ثان', phone, address: '', balance: 0, type: 'cash', creditLimit: 0, storeCreditBalance: 0 },
      auth,
    );
    assert.equal(createdB.ok, true);
    assert.notEqual(String(createdB.id), idA);
    assert.equal(createdB.phoneWarning.message, 'هذا الهاتف مسجل بالفعل للعميل عميل أول');
    assert.equal(createdB.phoneWarning.existingCustomer.id, idA);
    assert.equal(createdB.phoneWarning.existingCustomer.name, 'عميل أول');
    assert.equal(createdB.phoneWarning.existingCustomer.phone, phone);
    const rowB: any = await db.selectFrom('customers' as any).selectAll().where('id', '=', Number(createdB.id)).executeTakeFirst();
    assert.equal(rowB.phone, phone);
    const idB = String(createdB.id);

    // (3a) Move B to a fresh phone: allowed, no warning.
    const movedAway: any = await svc.updateCustomer(
      Number(idB),
      { name: 'عميل ثان', phone: '01111111111', address: '', balance: 0, type: 'cash', creditLimit: 0, storeCreditBalance: 0 },
      auth,
    );
    assert.equal(movedAway.ok, true);
    assert.equal(movedAway.phoneWarning, undefined);

    // (3b) Move B back to P: allowed, warned naming A (self excluded).
    const movedBack: any = await svc.updateCustomer(
      Number(idB),
      { name: 'عميل ثان', phone, address: '', balance: 0, type: 'cash', creditLimit: 0, storeCreditBalance: 0 },
      auth,
    );
    assert.equal(movedBack.ok, true);
    assert.equal(movedBack.phoneWarning.message, 'هذا الهاتف مسجل بالفعل للعميل عميل أول');
    assert.equal(movedBack.phoneWarning.existingCustomer.id, idA);

    // (4) A fresh phone: saved, no warning.
    const createdC: any = await svc.createCustomer(
      { name: 'عميل ثالث', phone: '01599999999', address: '', balance: 0, type: 'cash', creditLimit: 0, storeCreditBalance: 0 },
      auth,
    );
    assert.equal(createdC.ok, true);
    assert.equal(createdC.phoneWarning, undefined);

    // (5) A digit-variant of P (+2010... for stored 010...): warning still fires.
    const createdD: any = await svc.createCustomer(
      { name: 'عميل رابع', phone: '+201012345678', address: '', balance: 0, type: 'cash', creditLimit: 0, storeCreditBalance: 0 },
      auth,
    );
    assert.equal(createdD.ok, true);
    assert.equal(createdD.phoneWarning.message, 'هذا الهاتف مسجل بالفعل للعميل عميل أول');
    assert.equal(createdD.phoneWarning.existingCustomer.id, idA);

    console.log('Duplicate phone warn tests passed.');
  } finally {
    await db.destroy();
  }
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
