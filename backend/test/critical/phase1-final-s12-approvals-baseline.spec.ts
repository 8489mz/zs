/*
 * Phase 1 final-inspection slice 12 — baseline spec for the approvals
 * module (one of the 10 modules with zero primary specs on 95858d5).
 *
 * GROUNDING (live code, read before writing):
 * - ApprovalWorkflowService (approvals/approval-workflow.service.ts):
 *   Kysely + WhatsAppGatewayService (stubbed; only used by the
 *   non-blocking pending alert, never called here). Rules are
 *   purchase_orders-only, requiredRole admin-only; amounts validate
 *   min >= 0, max >= min; tiers validate >= 1. update/delete refuse
 *   while a pending request exists for the module (notes-only updates
 *   are exempt). checkAndInitiateApproval creates a pending request
 *   + an 'initiated' log row when an active rule matches the amount
 *   range, requires contiguous tiers from 1, and returns
 *   { requiresApproval: false } when no rule matches. approveRequest
 *   advances tiers and, on the final tier, transitions the purchase
 *   order pending_approval -> confirmed; rejectRequest needs a reason
 *   and transitions the order back to draft. A requester deciding
 *   their own request needs the solo-admin override (admin /
 *   super_admin) — the solo-admin spec (already linked) proves that
 *   path; this spec proves the rule lifecycle and the initiation
 *   path with a different decider.
 * - Real DDL (migration 2040000000071): approval_rules /
 *   approval_requests / approval_request_logs ids are BIGINT
 *   IDENTITY (the solo-admin spec's TEXT-id harness is its own
 *   fixture choice; this spec mirrors production).
 *
 * WHAT THIS PROVES (real service on PGlite):
 * - Rule CRUD: create defaults, manager-only gate, module/amount/
 *   tier/role validation, update (incl. the pending-request block
 *   and the notes-only exemption), delete (incl. the pending block
 *   and the missing-rule 404), tenant isolation.
 * - Initiation: no rule -> no approval; amount outside every rule
 *   range -> no approval; matching rules -> pending request + log
 *   row; tier gap -> error; getRequests / getPendingCount /
 *   getRequestDetails.
 * - Decision: two-tier approve advances then confirms the order;
 *   reject needs a reason and returns the order to draft.
 *
 * NOT RUN: the WhatsApp pending alert (non-blocking, stubbed),
 * UI, live Postgres.
 */

const DDL = `
  CREATE TABLE tenants (id text PRIMARY KEY);
  CREATE TABLE users (id bigint PRIMARY KEY, tenant_id text, username text, role text, is_active boolean DEFAULT true);
  CREATE TABLE approval_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL DEFAULT '',
    module TEXT NOT NULL,
    min_amount NUMERIC(15, 4) NOT NULL DEFAULT 0,
    max_amount NUMERIC(15, 4) NULL,
    tier_level INT NOT NULL DEFAULT 1,
    required_role TEXT NOT NULL DEFAULT 'admin',
    approver_user_id INT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE approval_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL DEFAULT '',
    module TEXT NOT NULL,
    record_id TEXT NOT NULL,
    record_ref TEXT NOT NULL DEFAULT '',
    amount NUMERIC(15, 4) NOT NULL DEFAULT 0,
    currency TEXT NOT NULL DEFAULT 'EGP',
    current_tier INT NOT NULL DEFAULT 1,
    max_tier INT NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'pending',
    requested_by INT NOT NULL,
    requested_by_name TEXT NULL,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE approval_request_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL DEFAULT '',
    request_id TEXT NOT NULL,
    tier_level INT NOT NULL DEFAULT 1,
    action TEXT NOT NULL,
    action_by BIGINT NULL,
    action_by_name TEXT NULL,
    action_role TEXT NULL,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE purchase_orders (
    id BIGINT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    account_id TEXT,
    order_number TEXT,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
`;

const admin1 = {
  tenantId: 't1',
  accountId: 'a1',
  role: 'admin',
  userId: 1,
  username: 'admin1',
  permissions: [],
} as unknown as AuthContext;
const admin2 = {
  tenantId: 't1',
  accountId: 'a1',
  role: 'admin',
  userId: 2,
  username: 'admin2',
  permissions: [],
} as unknown as AuthContext;
const cashier = {
  tenantId: 't1',
  accountId: 'a1',
  role: 'cashier',
  userId: 3,
  username: 'cashier3',
  permissions: [],
} as unknown as AuthContext;
const otherTenantAdmin = {
  tenantId: 't2',
  accountId: 'a2',
  role: 'admin',
  userId: 9,
  username: 'owner',
  permissions: [],
} as unknown as AuthContext;

async function makeDb(): Promise<{ pg: PGlite; db: Kysely<Database> }> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  await pg.exec(DDL);
  await pg.query(`INSERT INTO tenants VALUES ('t1'), ('t2')`);
  return { pg, db };
}

function buildService(db: Kysely<Database>): ApprovalWorkflowService {
  const whatsappStub = { sendRawMessage: async () => undefined };
  return new ApprovalWorkflowService(db, whatsappStub as unknown as never);
}

async function expectError(promise: Promise<unknown>, cls: new (...args: never[]) => Error): Promise<Error> {
  try {
    await promise;
  } catch (error) {
    assert.ok(error instanceof cls, `expected ${cls.name}, got ${String(error)}`);
    return error as Error;
  }
  assert.fail(`expected ${cls.name}, but the call succeeded`);
  throw new Error('unreachable');
}

async function main(): Promise<void> {
  // ---- Part A: rule CRUD + validation + pending-request block ----
  {
    const { pg, db } = await makeDb();
    try {
      const approvals = buildService(db);
      await pg.query(
        `INSERT INTO purchase_orders (id, tenant_id, account_id, order_number, status)
         VALUES (201, 't1', 'a1', 'PO-201', 'pending_approval')`,
      );

      await expectError(approvals.createRule({ module: 'purchase_orders' }, cashier), ForbiddenException);
      await expectError(approvals.getRules(cashier), ForbiddenException);

      const created = await approvals.createRule({ module: 'purchase_orders' }, admin1);
      assert.equal(created.ok, true, 'creating a rule succeeds');
      assert.equal(Number(created.rule.min_amount), 0, 'min defaults to 0');
      assert.equal(created.rule.max_amount, null, 'max defaults to null');
      assert.equal(Number(created.rule.tier_level), 1, 'tier defaults to 1');
      assert.equal(created.rule.required_role, 'admin', 'role defaults to admin');
      assert.equal(created.rule.is_active, true, 'the rule starts active');
      const ruleId = String(created.rule.id);

      await expectError(
        approvals.createRule({ module: 'sales' } as unknown as CreateApprovalRuleDto, admin1),
        BadRequestException,
      );
      await expectError(
        approvals.createRule({ module: 'purchase_orders', minAmount: -5 }, admin1),
        BadRequestException,
      );
      await expectError(
        approvals.createRule({ module: 'purchase_orders', minAmount: 100, maxAmount: 50 }, admin1),
        BadRequestException,
      );
      await expectError(approvals.createRule({ module: 'purchase_orders', tierLevel: 0 }, admin1), BadRequestException);
      await expectError(
        approvals.createRule({ module: 'purchase_orders', requiredRole: 'cashier' }, admin1),
        BadRequestException,
      );

      const listed = await approvals.getRules(admin1);
      assert.equal(listed.length, 1, 'one rule is listed');
      assert.equal((await approvals.getRules(otherTenantAdmin)).length, 0, 'rules are tenant-scoped');

      const updated = await approvals.updateRule(ruleId, { minAmount: 500, notes: 'high value only' }, admin1);
      assert.equal(Number(updated.rule.min_amount), 500, 'the min amount updates');
      assert.equal(updated.rule.notes, 'high value only', 'the notes update');

      // A pending request blocks non-notes updates and deletes.
      const initiated = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 201, recordRef: 'PO-201', amount: 600 },
        admin1,
      );
      assert.equal(initiated.requiresApproval, true, 'the 600 amount matches the 500+ rule');
      await expectError(approvals.updateRule(ruleId, { minAmount: 700 }, admin1), BadRequestException);
      const notesOnly = await approvals.updateRule(ruleId, { notes: 'still blocked otherwise' }, admin1);
      assert.equal(notesOnly.rule.notes, 'still blocked otherwise', 'a notes-only update is exempt from the block');
      await expectError(approvals.deleteRule(ruleId, admin1), BadRequestException);
      await expectError(approvals.deleteRule('999999', admin1), NotFoundException);

      // Resolve the request, then the rule can be deleted.
      const decided = await approvals.approveRequest(String(initiated.requestId), '', admin2);
      assert.equal(decided.status, 'approved', 'the single-tier request approves');
      const deleted = await approvals.deleteRule(ruleId, admin1);
      assert.equal(deleted.ok, true, 'the rule deletes once no request is pending');
      assert.equal((await approvals.getRules(admin1)).length, 0, 'no rules remain');
    } finally {
      await db.destroy();
    }
    console.log('  rule CRUD + validation + pending block passed');
  }

  // ---- Part B: initiation ranges, tier gaps, request reads ----
  {
    const { db } = await makeDb();
    try {
      const approvals = buildService(db);

      const none = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 301, recordRef: 'PO-301', amount: 100 },
        admin1,
      );
      assert.equal(none.requiresApproval, false, 'no rule means no approval');

      await approvals.createRule({ module: 'purchase_orders', minAmount: 1000, maxAmount: 2000, tierLevel: 1 }, admin1);
      const below = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 302, recordRef: 'PO-302', amount: 500 },
        admin1,
      );
      assert.equal(below.requiresApproval, false, 'below the range needs no approval');
      const above = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 303, recordRef: 'PO-303', amount: 3000 },
        admin1,
      );
      assert.equal(above.requiresApproval, false, 'above the range needs no approval');

      await approvals.createRule({ module: 'purchase_orders', minAmount: 1000, maxAmount: 2000, tierLevel: 2 }, admin1);
      const hit = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 304, recordRef: 'PO-304', amount: 1500 },
        admin1,
      );
      assert.equal(hit.requiresApproval, true, 'inside the range needs approval');
      assert.equal(hit.currentTier, 1, 'the request starts at tier 1');
      assert.equal(hit.maxTier, 2, 'the request spans both tiers');
      assert.equal(hit.status, 'pending', 'the request starts pending');
      assert.equal(await approvals.getPendingCount(admin1).then((r) => r.count), 1, 'one request is pending');
      const list = await approvals.getRequests({}, admin1);
      assert.equal(list.total, 1, 'one request is listed');
      assert.equal(list.items[0].record_ref, 'PO-304', 'the listed request is the initiated one');
      const details = await approvals.getRequestDetails(String(hit.requestId), admin1);
      assert.equal(details.logs.length, 1, 'one initiation log row exists');
      assert.equal(details.logs[0].action, 'initiated', 'the log action is initiated');
      assert.equal(details.rules.length, 2, 'both matching rules are returned');
      assert.equal(
        await approvals.getRequests({ status: 'approved' }, admin1).then((r) => r.total),
        0,
        'no approved requests yet',
      );

      // Tier gap: tiers 1 and 3 with no tier 2.
      const { db: db2 } = await makeDb();
      try {
        const approvals2 = buildService(db2);
        await approvals2.createRule({ module: 'purchase_orders', minAmount: 0, tierLevel: 1 }, admin1);
        await approvals2.createRule({ module: 'purchase_orders', minAmount: 0, tierLevel: 3 }, admin1);
        await expectError(
          approvals2.checkAndInitiateApproval(
            { module: 'purchase_orders', recordId: 305, recordRef: 'PO-305', amount: 10 },
            admin1,
          ),
          BadRequestException,
        );
      } finally {
        await db2.destroy();
      }
    } finally {
      await db.destroy();
    }
    console.log('  initiation ranges + tier gap + request reads passed');
  }

  // ---- Part C: two-tier approve confirms the order; reject returns it to draft ----
  {
    const { pg, db } = await makeDb();
    try {
      const approvals = buildService(db);
      await pg.query(
        `INSERT INTO purchase_orders (id, tenant_id, account_id, order_number, status) VALUES
         (401, 't1', 'a1', 'PO-401', 'pending_approval'),
         (402, 't1', 'a1', 'PO-402', 'pending_approval')`,
      );
      await approvals.createRule({ module: 'purchase_orders', minAmount: 0, tierLevel: 1 }, admin1);
      await approvals.createRule({ module: 'purchase_orders', minAmount: 0, tierLevel: 2 }, admin1);

      const two = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 401, recordRef: 'PO-401', amount: 100 },
        admin1,
      );
      const first = await approvals.approveRequest(String(two.requestId), '', admin2);
      assert.equal(first.status, 'pending', 'the first tier leaves the request pending');
      assert.equal(first.currentTier, 2, 'the request advances to tier 2');
      const poMid = await pg.query<{ status: string }>(`SELECT status FROM purchase_orders WHERE id=401`);
      assert.equal(poMid.rows[0].status, 'pending_approval', 'the order stays pending after tier 1');
      const second = await approvals.approveRequest(String(two.requestId), '', admin2);
      assert.equal(second.status, 'approved', 'the final tier approves');
      assert.equal(second.isFullyApproved, true, 'the final tier fully approves');
      const poDone = await pg.query<{ status: string }>(`SELECT status FROM purchase_orders WHERE id=401`);
      assert.equal(poDone.rows[0].status, 'confirmed', 'the order confirms on final approval');
      await expectError(approvals.approveRequest(String(two.requestId), '', admin2), BadRequestException);

      const one = await approvals.checkAndInitiateApproval(
        { module: 'purchase_orders', recordId: 402, recordRef: 'PO-402', amount: 100 },
        admin1,
      );
      await expectError(approvals.rejectRequest(String(one.requestId), '   ', admin2), BadRequestException);
      const rejected = await approvals.rejectRequest(String(one.requestId), 'السعر مرتفع', admin2);
      assert.equal(rejected.status, 'rejected', 'the request rejects with a reason');
      const poBack = await pg.query<{ status: string }>(`SELECT status FROM purchase_orders WHERE id=402`);
      assert.equal(poBack.rows[0].status, 'draft', 'the order returns to draft on rejection');
      assert.equal((await approvals.getPendingCount(admin1)).count, 0, 'no requests are pending anymore');
    } finally {
      await db.destroy();
    }
    console.log('  two-tier approve + reject passed');
  }

  console.log('phase1 final slice 12 approvals baseline passed');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
