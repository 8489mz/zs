/*
 * Phase 1 final-inspection slice 12 — baseline spec for the addons
 * module (one of the 10 modules with zero primary specs on 95858d5).
 *
 * GROUNDING (live code, read before writing):
 * - AddonsService (addons/addons.service.ts): Kysely + AuditService
 *   stub. Addon CRUD with a service-level non-negative price guard
 *   (ADDON_PRICE_INVALID, 400) and 404 ADDON_NOT_FOUND. Modifier
 *   groups: create inserts the group + its options in one
 *   transaction; update replaces the options and — R4-C I49 — keeps
 *   the stored displayOrder / isActive / isSplittableInHalf when the
 *   payload omits them; delete removes options, product links and
 *   the group. getProductModifiers — R4-C I50 — returns [] for an
 *   unlinked product (never every active group); linkProductModifiers
 *   replaces the product's links.
 * - DDL mirrors the real migrations (2030000000008 addons;
 *   2040000000065 modifier tables; 2040000000227
 *   is_splittable_in_half; later option columns
 *   component_product_id / consumption_qty / unit_name /
 *   portion_allowed / preparation_time_minutes); products is a
 *   minimal harness table for the component join.
 *
 * WHAT THIS PROVES (real service on PGlite):
 * - Addon CRUD: negative/NaN price refused, defaults, tenant
 *   isolation, update, delete + missing 404.
 * - Modifier groups: create with options, negative option price
 *   refused, update replaces options, unsent displayOrder/isActive
 *   keep their stored values, delete removes group + options.
 * - Product linking: unlinked product shows no groups, linking
 *   shows the group with its options, unlinking hides them again,
 *   deleting the group removes the link.
 *
 * NOT RUN: DTO/controller validation, POS rendering, UI, live
 * Postgres.
 */

const DDL = `
  CREATE TABLE addons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    account_id TEXT NOT NULL,
    name TEXT NOT NULL,
    price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    cost_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE pos_modifier_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    account_id TEXT NOT NULL,
    name TEXT NOT NULL,
    name_en TEXT NULL,
    selection_type TEXT NOT NULL DEFAULT 'multiple',
    is_mandatory BOOLEAN NOT NULL DEFAULT FALSE,
    min_selections INTEGER NOT NULL DEFAULT 0,
    max_selections INTEGER NOT NULL DEFAULT 10,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_splittable_in_half BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE pos_modifier_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    account_id TEXT NOT NULL,
    group_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    name_en TEXT NULL,
    price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    cost_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    component_product_id BIGINT NULL,
    consumption_qty NUMERIC(14, 3) NULL,
    unit_name TEXT NULL,
    portion_allowed TEXT NOT NULL DEFAULT 'both',
    preparation_time_minutes INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE product_pos_modifiers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    account_id TEXT NOT NULL,
    product_id BIGINT NOT NULL,
    modifier_group_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    name TEXT NOT NULL
  );
`;

const auth = {
  tenantId: 't1',
  accountId: 'a1',
  userId: 1,
  username: 'admin',
  role: 'admin',
  permissions: [],
} as unknown as AuthContext;
const otherTenantAuth = {
  tenantId: 't2',
  accountId: 'a2',
  userId: 9,
  username: 'owner',
  role: 'admin',
  permissions: [],
} as unknown as AuthContext;

async function makeDb(): Promise<{ pg: PGlite; db: Kysely<Database> }> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  await pg.exec(DDL);
  return { pg, db };
}

function buildService(db: Kysely<Database>): AddonsService {
  const audit = { log: async () => undefined };
  return new AddonsService(db, audit as unknown as never);
}

async function expectAppError(promise: Promise<unknown>, code: string, status: number): Promise<void> {
  try {
    await promise;
  } catch (error) {
    assert.ok(error instanceof AppError, `expected AppError, got ${String(error)}`);
    const appError = error as AppError;
    assert.equal(appError.code, code, `expected code ${code}, got ${appError.code}`);
    assert.equal(appError.statusCode, status, `expected status ${status}, got ${appError.statusCode}`);
    return;
  }
  assert.fail(`expected AppError ${code}, but the call succeeded`);
}

async function main(): Promise<void> {
  // ---- Part A: addon CRUD + price guard ----
  {
    const { db } = await makeDb();
    try {
      const addons = buildService(db);

      await expectAppError(addons.createAddon({ name: 'x', price: -5 } as never, auth), 'ADDON_PRICE_INVALID', 400);
      await expectAppError(
        addons.createAddon({ name: 'x', price: 10, costPrice: -1 } as never, auth),
        'ADDON_PRICE_INVALID',
        400,
      );
      await expectAppError(
        addons.createAddon({ name: 'x', price: Number.NaN } as never, auth),
        'ADDON_PRICE_INVALID',
        400,
      );

      const created = await addons.createAddon({ name: 'جبنة إضافية', price: 15, costPrice: 8 } as never, auth);
      assert.equal(created.ok, true, 'creating an addon succeeds');
      const addonId = Number(created.id);
      const listed = await addons.listAddons(auth);
      assert.equal(listed.addons.length, 1, 'one addon is listed');
      assert.equal(listed.addons[0].name, 'جبنة إضافية', 'the addon name is stored');
      assert.equal(listed.addons[0].price, 15, 'the addon price is stored');
      assert.equal(listed.addons[0].costPrice, 8, 'the addon cost price is stored');
      assert.equal(listed.addons[0].isActive, true, 'the addon starts active');
      assert.equal((await addons.listAddons(otherTenantAuth)).addons.length, 0, 'addons are tenant-scoped');

      const updated = await addons.updateAddon(
        addonId,
        { name: 'جبنة إضافية', price: 20, costPrice: 8 } as never,
        auth,
      );
      assert.equal(updated.ok, true, 'updating succeeds');
      assert.equal((await addons.listAddons(auth)).addons[0].price, 20, 'the price updates');
      await expectAppError(addons.updateAddon(999999, { name: 'x', price: 1 } as never, auth), 'ADDON_NOT_FOUND', 404);

      const deleted = await addons.deleteAddon(addonId, auth);
      assert.equal(deleted.ok, true, 'deleting succeeds');
      assert.equal((await addons.listAddons(auth)).addons.length, 0, 'no addons remain');
      await expectAppError(addons.deleteAddon(addonId, auth), 'ADDON_NOT_FOUND', 404);
    } finally {
      await db.destroy();
    }
    console.log('  addon CRUD + price guard passed');
  }

  // ---- Part B: modifier group lifecycle ----
  {
    const { db } = await makeDb();
    try {
      const addons = buildService(db);

      await expectAppError(
        addons.createModifierGroup({ name: 'إضافات', options: [{ name: 'جبنة', price: -3 }] }, auth),
        'MODIFIER_OPTION_PRICE_INVALID',
        400,
      );

      const created = await addons.createModifierGroup(
        {
          name: 'درجة الطهي',
          selectionType: 'single',
          isMandatory: true,
          displayOrder: 5,
          isActive: false,
          options: [
            { name: 'وسط', price: 0, isDefault: true },
            { name: 'ويل دن', price: 10, costPrice: 4 },
          ],
        },
        auth,
      );
      assert.equal(created.ok, true, 'creating a group succeeds');
      const groupId = Number(created.id);
      const listed = await addons.listModifierGroups(auth);
      assert.equal(listed.groups.length, 1, 'one group is listed');
      assert.equal(listed.groups[0].selectionType, 'single', 'the selection type is stored');
      assert.equal(listed.groups[0].isMandatory, true, 'the mandatory flag is stored');
      assert.equal(listed.groups[0].displayOrder, 5, 'the display order is stored');
      assert.equal(listed.groups[0].isActive, false, 'the active flag is stored');
      assert.equal(listed.groups[0].options.length, 2, 'both options are listed');
      assert.equal(listed.groups[0].options[0].isDefault, true, 'the first option is the default');
      assert.equal(listed.groups[0].options[1].price, 10, 'the second option price is stored');
      assert.equal(listed.groups[0].options[1].costPrice, 4, 'the second option cost is stored');

      // R4-C I49: an update that omits displayOrder/isActive keeps them.
      const updated = await addons.updateModifierGroup(
        groupId,
        {
          name: 'درجة الطهي (محدث)',
          options: [{ name: 'نادر', price: 5 }],
        },
        auth,
      );
      assert.equal(updated.ok, true, 'updating the group succeeds');
      const after = await addons.listModifierGroups(auth);
      assert.equal(after.groups[0].name, 'درجة الطهي (محدث)', 'the name updates');
      assert.equal(after.groups[0].displayOrder, 5, 'the display order is kept when unsent');
      assert.equal(after.groups[0].isActive, false, 'the active flag is kept when unsent');
      assert.equal(after.groups[0].options.length, 1, 'the options are replaced');
      assert.equal(after.groups[0].options[0].name, 'نادر', 'the new option is stored');
      await expectAppError(addons.updateModifierGroup(999999, { name: 'x' }, auth), 'MODIFIER_GROUP_NOT_FOUND', 404);

      const deleted = await addons.deleteModifierGroup(groupId, auth);
      assert.equal(deleted.ok, true, 'deleting the group succeeds');
      assert.equal((await addons.listModifierGroups(auth)).groups.length, 0, 'no groups remain');
    } finally {
      await db.destroy();
    }
    console.log('  modifier group lifecycle passed');
  }

  // ---- Part C: product linking (I50) ----
  {
    const { pg, db } = await makeDb();
    try {
      const addons = buildService(db);
      const product = await pg.query<{ id: string }>(
        `INSERT INTO products (tenant_id, name) VALUES ('t1', 'بيتزا مارجريتا') RETURNING id`,
      );
      const productId = Number(product.rows[0].id);
      const group = await addons.createModifierGroup(
        {
          name: 'إضافات البيتزا',
          options: [{ name: 'جبنة إضافية', price: 15 }],
        },
        auth,
      );
      const groupId = Number(group.id);

      const unlinked = await addons.getProductModifiers(productId, auth);
      assert.equal(unlinked.groups.length, 0, 'an unlinked product shows no groups');

      const linked = await addons.linkProductModifiers(productId, [groupId], auth);
      assert.equal(linked.ok, true, 'linking succeeds');
      const shown = await addons.getProductModifiers(productId, auth);
      assert.equal(shown.groups.length, 1, 'the linked group shows');
      assert.equal(shown.groups[0].name, 'إضافات البيتزا', 'the linked group is the created one');
      assert.equal(shown.groups[0].options.length, 1, 'the linked group options show');
      assert.equal(shown.groups[0].options[0].price, 15, 'the option price shows');

      await addons.linkProductModifiers(productId, [], auth);
      const unlinkedAgain = await addons.getProductModifiers(productId, auth);
      assert.equal(unlinkedAgain.groups.length, 0, 'unlinking hides the group again');

      await addons.linkProductModifiers(productId, [groupId], auth);
      await addons.deleteModifierGroup(groupId, auth);
      const afterDelete = await addons.getProductModifiers(productId, auth);
      assert.equal(afterDelete.groups.length, 0, 'deleting the group removes the link');
    } finally {
      await db.destroy();
    }
    console.log('  product linking passed');
  }

  console.log('phase1 final slice 12 addons baseline passed');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
