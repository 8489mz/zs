/*
New file: backend/test/critical/services-amount-3dp.spec.ts
Pins INV-SERVICES-AMOUNT-3DP (S1 of the critical-17 chain).

THE GAP: services.amount was still NUMERIC(14,2) — the 0256-0278
widening migrations never mention the services table. On a 3dp tenant
(KWD) a 10.125 service was stored/posted as 10.13 (0.005 loss) and the
audit log printed the input 10.125 against the journal 10.13. The fix
is the 0317 migration widening services.amount to numeric(15,3); no
code change was needed because postService already rounds through
toBookMoney at the tenant's book digits, createService stores the
plain Number, listServices rounds at book digits, and the audit log
prints toFixed(digits).

WHAT THIS PINS, driving the REAL ServicesService.createService on
PGlite with a KWD tenant (no copies of the rounding math):
- The migration itself: services.amount starts at numeric_scale 2
  (production DDL at the base) and the 0317 up() widens it to scale 3
  (precision 15). This is the migration-presence proof: rename the
  migration file away and this spec fails to load.
- A cash service created with amount 10.125 reads back exactly
  10.125 from services.amount.
- The posted journal (Dr 1110 / Cr 4200) is exactly 10.125 on both
  legs, not 10.13, and balances.
- The treasury cash_in row is exactly 10.125.
- The audit log prints 10.125 (never 10.13).
- listServices (inside the create response) totals 10.125.
*/

