/*
 * Pins W3 (unification batch U4): broker capitalization + lot allocation
 * canonical digits.
 *
 * VERDICT 1 — BROKER CAPITALIZATION IS CLASSIFICATION ONLY (no money
 * math, no allocation change). resolveBrokerCapitalizationBucket +
 * BROKER_CAPITALIZATION_BUCKETS is a pure category -> shipment-cost-
 * bucket map: every map value is a bucket-name string or null, and
 * every resolver result is { bucket, reason } with no numeric field.
 * The money fold lives in import-sales.service.ts and is a single
 * amount into a single bucket column (coalesce(bucket, 0) + amount);
 * there are no weights and no remainder to split, so the canonical
 * allocateLandedCosts engine does not apply there. This phase pins
 * the mapping and the no-numbers shape so a future money-math
 * addition cannot slip in unnoticed.
 *
 * VERDICT 2 — LOT GROSS MARGINS USE EGP DIGITS (2), NOT TENANT BOOK
 * DIGITS. gross_margin_egp is EGP-denominated (column name, and
 * NUMERIC(15, 2) in migration 2040000000239), so digits follow the
 * denomination, not the tenant (binding policy decision, supersedes
 * the D6c choice that stored KWD-tenant margins at 3dp). A margin
 * that would be 100.125 at 3dp is stored 100.13 on a KWD tenant.
 * All three stored-margin sites are pinned here: sale allocation,
 * cancel-restore, and return-restore (D6c pinned only the first
 * two). The helper no longer resolves tenant currency at all, so a
 * phase with no settings / currency tables runs and still stores
 * 100.13 — the old code threw reading settings there.
 *
 * VERDICT 3 — SALE-COST TOTAL IS EGP-DENOMINATED AND ALREADY USES 2.
 * calculateImportSaleCost defaults to currencyMoneyDigits('EGP')
 * and its only live caller (import-sales.service.ts preorder
 * conversion) passes no moneyDigits, so the live total is EGP 2dp
 * with no code change. The optional moneyDigits param is unchanged
 * (D6c Phase C still pins an explicit 3-digit call); it is a
 * caller-supplied override, not the live path.
 *
 * LIVE-CALLER WIRING: the helper gains NO digits param — it resolves
 * EGP digits internally from the denomination constant — so no live
 * caller needs a change: sales-write.service.ts (allocate x2,
 * cancel-restore x2), returns.service.ts (return-restore) and
 * import-sales.service.ts (allocate + sale cost) already invoke
 * these exact functions on their transaction handle, and phases B/C
 * drive those same functions on a real PGlite transaction.
 */

import 'reflect-metadata';
import { strict as assert } from 'node:assert';
import { PGlite } from '@electric-sql/pglite';
import { Kysely, sql } from 'kysely';
import { PGliteDialect } from 'kysely-pglite-dialect';
import { Database } from '../../src/database/database.types';
import {
  BROKER_CAPITALIZATION_BUCKETS,
  resolveBrokerCapitalizationBucket,
} from '../../src/modules/import-sales/engines/import-broker-capitalization.engine';
import {
  allocateSaleFromImportLots,
  calculateImportSaleCost,
  restoreImportLotsFromCancelledSale,
  restoreImportLotsFromSalesReturn,
} from '../../src/modules/import-sales/helpers/import-lot-allocation.helper';

async function makeDb(): Promise<{ pg: PGlite; db: Kysely<Database> }> {
  const pg = new PGlite();
  const db = new Kysely<Database>({ dialect: new PGliteDialect(pg) });
  return { pg, db };
}

async function seedCurrency(db: Kysely<Database>, tenantId: string, currency: string): Promise<void> {
  await sql`CREATE TABLE IF NOT EXISTS settings (tenant_id text, key text, value text, PRIMARY KEY (tenant_id, key))`.execute(db);
  await sql`CREATE TABLE IF NOT EXISTS currency_exchange_rates (tenant_id text, currency_code text, is_base boolean, exchange_rate numeric)`.execute(db);
  await sql`INSERT INTO settings (tenant_id, key, value) VALUES (${tenantId}, 'currency', ${currency})`.execute(db);
  await sql`INSERT INTO currency_exchange_rates (tenant_id, currency_code, is_base, exchange_rate) VALUES (${tenantId}, ${currency}, true, 1)`.execute(db);
}

const LOT_TABLES = `
  CREATE TABLE import_inventory_lots (id bigint PRIMARY KEY, tenant_id text, product_id bigint, status text, remaining_quantity numeric, location_id bigint, receipt_date timestamptz, created_at timestamptz, updated_at timestamptz, unit_landed_cost_egp numeric, project_id bigint, shipment_id bigint);
  CREATE TABLE import_sale_allocations (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id text, sale_id bigint, sale_item_id bigint, lot_id bigint, project_id bigint, shipment_id bigint, product_id bigint, quantity numeric, unit_sale_price_egp numeric, unit_cost_egp numeric, gross_margin_egp numeric, allocation_type text, reversal_of_allocation_id bigint, created_at timestamptz);
`;

async function main(): Promise<void> {
  // Phase A: broker capitalization is classification only.
  {
    // No numbers anywhere in the map: bucket names or null only.
    for (const value of Object.values(BROKER_CAPITALIZATION_BUCKETS)) {
      assert.ok(value === null || typeof value === 'string', 'bucket map must hold names or null, never a number');
    }
    const cases: Array<[string, boolean, string | null, string]> = [
      ['customs_duty', false, 'customs_cost_egp', 'ok'],
      ['port_fees', false, 'customs_cost_egp', 'ok'],
      ['inspection', false, 'customs_cost_egp', 'ok'],
      ['broker_fee', false, 'customs_cost_egp', 'ok'],
      ['demurrage', false, 'actual_demurrage_fees', 'ok'],
      ['transport', false, 'internal_transport_cost_egp', 'ok'],
      ['vat', true, null, 'vat_asset'],
      ['vat', false, null, 'no_bucket'],
      ['other', false, null, 'no_bucket'],
      ['unknown_category', false, null, 'no_bucket'],
    ];
    for (const [category, refundable, bucket, reason] of cases) {
      const result = resolveBrokerCapitalizationBucket(category, refundable);
      assert.equal(result.bucket, bucket);
      assert.equal(result.reason, reason);
      // The resolver result carries no money: no numeric field at all.
      assert.ok(Object.values(result).every((v) => typeof v !== 'number'), 'resolver result must carry no money math');
    }
    console.log('phase A broker classification-only passed');
  }

  // Phase B: lot margins at EGP digits (2) on a KWD tenant — all three
  // stored-margin sites, driven on a real PGlite transaction (the exact
  // functions the live callers invoke). Raw margin 100.125 -> 100.13.
  {
    const { pg, db } = await makeDb();
    try {
      await pg.exec(LOT_TABLES);
      await pg.exec(`
        INSERT INTO import_inventory_lots VALUES (1, 't1', 7, 'active', 10, 5, NOW(), NOW(), NOW(), 10.0125, NULL, NULL), (2, 't3', 7, 'active', 10, 5, NOW(), NOW(), NOW(), 10.0125, NULL, NULL);
      `);
      await seedCurrency(db, 't1', 'KWD');
      await seedCurrency(db, 't3', 'EGP');
      await db.transaction().execute(async (trx) => {
        await allocateSaleFromImportLots(trx as never, {
          tenantId: 't1', saleId: 1, locationId: 5,
          items: [{ productId: 7, qty: 1, netUnitPrice: 110.1375 }],
        });
        await allocateSaleFromImportLots(trx as never, {
          tenantId: 't3', saleId: 2, locationId: 5,
          items: [{ productId: 7, qty: 1, netUnitPrice: 110.1375 }],
        });
      });
      const kwdAlloc = await db.selectFrom('import_sale_allocations').selectAll().where('tenant_id', '=', 't1').executeTakeFirstOrThrow();
      const egpAlloc = await db.selectFrom('import_sale_allocations').selectAll().where('tenant_id', '=', 't3').executeTakeFirstOrThrow();
      assert.equal(Number(kwdAlloc.gross_margin_egp), 100.13);
      assert.equal(Number(egpAlloc.gross_margin_egp), 100.13);
      // Cancel-restore (site 2): reversal is the EGP-rounded negation.
      await db.transaction().execute(async (trx) => {
        await restoreImportLotsFromCancelledSale(trx as never, { tenantId: 't1', saleId: 1 });
      });
      const cancelReversal = await db.selectFrom('import_sale_allocations').selectAll().where('tenant_id', '=', 't1').where('allocation_type', '=', 'cancellation').executeTakeFirstOrThrow();
      assert.equal(Number(cancelReversal.gross_margin_egp), -100.13);
      // Return-restore (site 3): allocate a fresh sale, then return it.
      await db.transaction().execute(async (trx) => {
        await allocateSaleFromImportLots(trx as never, {
          tenantId: 't1', saleId: 3, locationId: 5,
          items: [{ productId: 7, qty: 1, netUnitPrice: 110.1375 }],
        });
      });
      await db.transaction().execute(async (trx) => {
        await restoreImportLotsFromSalesReturn(trx as never, {
          tenantId: 't1', saleId: 3, productId: 7, returnQty: 1,
        });
      });
      const returnReversal = await db.selectFrom('import_sale_allocations').selectAll().where('tenant_id', '=', 't1').where('sale_id', '=', 3).where('allocation_type', '=', 'return').executeTakeFirstOrThrow();
      assert.equal(Number(returnReversal.gross_margin_egp), -100.13);
      console.log('phase B lot margins at EGP digits passed');
    } finally {
      await db.destroy();
    }
  }

  // Phase C: the helper no longer resolves tenant currency — with no
  // settings / currency_exchange_rates tables at all it still allocates
  // and stores the margin at EGP digits (old code threw here).
  {
    const { pg, db } = await makeDb();
    try {
      await pg.exec(LOT_TABLES);
      await pg.exec(`
        INSERT INTO import_inventory_lots VALUES (1, 't9', 7, 'active', 10, 5, NOW(), NOW(), NOW(), 10.0125, NULL, NULL);
      `);
      await db.transaction().execute(async (trx) => {
        await allocateSaleFromImportLots(trx as never, {
          tenantId: 't9', saleId: 1, locationId: 5,
          items: [{ productId: 7, qty: 1, netUnitPrice: 110.1375 }],
        });
      });
      const alloc = await db.selectFrom('import_sale_allocations').selectAll().where('tenant_id', '=', 't9').executeTakeFirstOrThrow();
      assert.equal(Number(alloc.gross_margin_egp), 100.13);
      console.log('phase C no-settings allocation passed');
    } finally {
      await db.destroy();
    }
  }

  // Phase D: the sale-cost total is EGP-denominated — the live default
  // (no moneyDigits passed, as the preorder-conversion caller does)
  // rounds to EGP 2dp: 66.75 + 1 x 16.6875 = 83.4375 -> 83.44.
  {
    const saleCost = calculateImportSaleCost({ qty: 3, allocatedQty: 2, allocCostEgp: 66.75, fallbackUnitCostEgp: 16.6875 });
    assert.equal(saleCost.totalCostEgp, 83.44);
    assert.equal(saleCost.shortfallQty, 1);
    assert.equal(saleCost.unitCostEgp, 27.813333);
    console.log('phase D sale-cost total at EGP digits passed');
  }
}

main().then(
  () => console.log('import-broker-lot-canonical: all phases passed'),
  (err) => { console.error(err); process.exit(1); },
);
