import { usePurchaseOrderFormState } from './hooks/use-purchase-order-form-state';
import { usePurchaseOrderDraft } from './hooks/use-purchase-order-draft';
import { usePurchaseOrderCatalog } from './hooks/use-purchase-order-catalog';
import { usePurchaseOrderMoney } from './hooks/use-purchase-order-money';
import { usePurchaseOrderLines } from './hooks/use-purchase-order-lines';
import { usePurchaseOrderQuickCreate } from './hooks/use-purchase-order-quick-create';
import { usePurchaseOrderValidation } from './hooks/use-purchase-order-validation';
import { usePurchaseOrderSubmit } from './hooks/use-purchase-order-submit';
import { usePurchaseOrderEffects } from './hooks/use-purchase-order-effects';

export function useNewPurchaseOrderController() {
  const s1 = usePurchaseOrderFormState();
  const {queryClient, t, language, theme, isDarkMode, activeQuickAction, setActiveQuickAction,
    discountMode, setDiscountMode, customTaxRate, setCustomTaxRate, pendingFocusLineId,
    setPendingFocusLineId, lines, setLines, supplier, setSupplier, paymentType, setPaymentType,
    date, setDate, requiredDate, setRequiredDate, currency, setCurrency, company, setCompany,
    contact, setContact, shippingAddress, setShippingAddress, taxRate, setTaxRate, discount,
    setDiscount, costCenter, setCostCenter, project, setProject, termsTemplate, setTermsTemplate,
    notes, setNotes, attachments, setAttachments, isUploading, setIsUploading,
    pendingFocusQtyLineId, setPendingFocusQtyLineId, quickCreateState, setQuickCreateState,
    productCreateModalState, setProductCreateModalState, barcodeScanOpen, setBarcodeScanOpen,
    barcodeScanQuery, setBarcodeScanQuery, createdPurchase, setCreatedPurchase, isPolling,
    setIsPolling, idempotencyKeyRef, currentPayloadRef, navigate, catalog, resetFormFields} = s1;
  const s3 = usePurchaseOrderDraft({lines, supplier, date, requiredDate, currency, company, contact,
    shippingAddress, taxRate, discount, discountMode, customTaxRate, costCenter, project,
    termsTemplate, notes, isDarkMode, setSupplier, setDate, setRequiredDate, setCurrency,
    setCompany, setContact, setShippingAddress, setTaxRate, setDiscount, setDiscountMode,
    setCustomTaxRate, setCostCenter, setProject, setTermsTemplate, setNotes, setLines});
  const {supplierInputRef, dateInputRef, requiredDateInputRef, currencyInputRef, contactInputRef,
    shippingInputRef, costCenterInputRef, projectInputRef, lastSavedSnapshotRef, hasLoadedDraftRef,
    documentStatus, setDocumentStatus, validationErrors, setValidationErrors, inlineMessage,
    setInlineMessage, purchaseDropdownClassName, setLineError, clearLineErrors,
    clearDocumentFieldError, markDocumentDirty, buildDraftPayload, saveDraftToStorage,
    restoreDraftFromStorage, computeHasMeaningfulData} = s3;
  const s2 = usePurchaseOrderCatalog({catalog, resetFormFields, setCreatedPurchase, supplier,
    draftUi: { hasLoadedDraftRef, setValidationErrors, setInlineMessage, setDocumentStatus },
    shippingAddress, setShippingAddress, currency, setCurrency});
  const {createMutation, rawSettings, rawLocations, rawBranches, rawCategories, suppliers,
    setSuppliers, products, setProducts, warehouses, setWarehouses, categories,
    deliveryDestinations, costCenters, setCostCenters, projects, setProjects, contactsList,
    setContactsList, addressesList, setAddressesList} = s2;
  const s4 = usePurchaseOrderMoney({lines, discountMode, discount, taxRate});
  const {subtotal, tax, total} = s4;
  const s5 = usePurchaseOrderLines({markDocumentDirty, clearLineErrors, clearDocumentFieldError,
    setLineError, contactInputRef, setLines, setPendingFocusLineId, setBarcodeScanQuery,
    setBarcodeScanOpen, setSupplier, setCompany, setContact, setShippingAddress, setCostCenter,
    setProject, setPendingFocusQtyLineId, rawCategories, rawLocations, setProducts, rawSettings,
    products, catalog});
  const {addLine, handleBarcodeScanAction, addServiceLine, removeLine, updateLine, createEntityId,
    handleSupplierSelect, handleContactSelect, handleAddressSelect, handleWarehouseSelect,
    handleCategorySelect, searchCategory, handleCostCenterSelect, handleProjectSelect,
    fetchProductOptions, handleProductSelect, addProductAsLine, incrementProductByBarcode} = s5;
  const s6 = usePurchaseOrderQuickCreate({markDocumentDirty, createEntityId, handleSupplierSelect,
    handleContactSelect, handleAddressSelect, handleCostCenterSelect, handleProjectSelect,
    handleProductSelect, addProductAsLine, incrementProductByBarcode, suppliers, setSuppliers,
    products, setProducts, warehouses, setWarehouses, costCenters, setCostCenters, projects,
    setProjects, setContactsList, setAddressesList, company, setContact, setInlineMessage,
    queryClient, quickCreateState, setProductCreateModalState, setQuickCreateState,
    setBarcodeScanOpen, productCreateModalState});
  const {handleQuickCreateSubmit, openQuickCreate, openProductQuickCreateFromBarcode,
    handleProductCreateSuccess, closeProductCreateModal, handleBarcodeScanSubmit, closeQuickCreate} = s6;
  const s7 = usePurchaseOrderValidation({markDocumentDirty, setTaxRate, setCustomTaxRate,
    setActiveQuickAction, customTaxRate, supplierInputRef, dateInputRef, requiredDateInputRef,
    currencyInputRef, suppliers, supplier, t, date, requiredDate, currency, lines, products});
  const {applyTaxPreset, applyCustomTaxRate, applyDiscount, focusFirstInvalidField,
    validateBeforeConfirm} = s7;
  const s8 = usePurchaseOrderSubmit({hasLoadedDraftRef, setSupplier, setDate, setRequiredDate,
    setCurrency, setCompany, setContact, setShippingAddress, setTaxRate, setDiscount, setCostCenter,
    setProject, setTermsTemplate, setNotes, setLines, setAttachments, setDocumentStatus,
    setInlineMessage, computeHasMeaningfulData, t, saveDraftToStorage, setValidationErrors,
    validateBeforeConfirm, focusFirstInvalidField, suppliers, supplier, contactsList, contact,
    addressesList, shippingAddress, costCenters, costCenter, projects, project, products,
    warehouses, paymentType, discount, rawBranches, rawLocations, notes, requiredDate, currency,
    company, termsTemplate, lines, setIsPolling, taxRate, attachments, idempotencyKeyRef,
    currentPayloadRef, createMutation, setIsUploading});
  const {handleResetDraft, handleSaveDraft, handleConfirmInvoice, handleFileUpload,
    handleRemoveAttachment} = s8;
  const s9 = usePurchaseOrderEffects({hasLoadedDraftRef, restoreDraftFromStorage,
    computeHasMeaningfulData, lastSavedSnapshotRef, buildDraftPayload, documentStatus,
    inlineMessage, setInlineMessage, supplier, date, requiredDate, currency, company, contact,
    shippingAddress, discount, customTaxRate, costCenter, project, termsTemplate, notes, lines,
    taxRate, discountMode, pendingFocusLineId, setPendingFocusLineId, pendingFocusQtyLineId,
    setPendingFocusQtyLineId, t, setCreatedPurchase, resetFormFields, suppliers, contactsList,
    addressesList, products, warehouses, costCenters, projects, setSuppliers, setContactsList,
    draftUi: { hasLoadedDraftRef, setValidationErrors, setInlineMessage, setDocumentStatus },
    setAddressesList, setProducts, setWarehouses, setCostCenters, setProjects});
  const {handleNewPurchaseOrder} = s9;

  return {
    t,
    language,
    theme,
    isDarkMode,
    activeQuickAction,
    setActiveQuickAction,
    discountMode,
    setDiscountMode,
    customTaxRate,
    setCustomTaxRate,
    pendingFocusLineId,
    lines,
    setLines,
    supplier,
    setSupplier,
    paymentType,
    setPaymentType,
    date,
    setDate,
    requiredDate,
    setRequiredDate,
    currency,
    setCurrency,
    company,
    contact,
    setContact,
    shippingAddress,
    setShippingAddress,
    taxRate,
    setTaxRate,
    discount,
    setDiscount,
    costCenter,
    setCostCenter,
    project,
    setProject,
    termsTemplate,
    setTermsTemplate,
    notes,
    setNotes,
    attachments,
    isUploading,
    quickCreateState,
    setQuickCreateState,
    productCreateModalState,
    setProductCreateModalState,
    barcodeScanOpen,
    setBarcodeScanOpen,
    barcodeScanQuery,
    createdPurchase,
    isPolling,
    navigate,
    createMutation,
    rawSettings,
    suppliers,
    products,
    warehouses,
    categories,
    contactsList,
    addressesList,
    costCenters,
    projects,
    validationErrors,
    documentStatus,
    inlineMessage,
    subtotal,
    tax,
    total,
    deliveryDestinations,
    supplierInputRef,
    dateInputRef,
    requiredDateInputRef,
    currencyInputRef,
    contactInputRef,
    shippingInputRef,
    costCenterInputRef,
    projectInputRef,
    purchaseDropdownClassName,
    markDocumentDirty,
    clearDocumentFieldError,
    handleSupplierSelect,
    handleContactSelect,
    handleAddressSelect,
    handleCategorySelect,
    handleWarehouseSelect,
    handleCostCenterSelect,
    handleProjectSelect,
    handleProductSelect,
    addProductAsLine,
    updateLine,
    addLine,
    addServiceLine,
    addProductLine: () => s5.addProductLine(s6.openQuickCreate),
    removeLine,
    setLineError,
    fetchProductOptions,
    searchCategory,
    handleBarcodeScanAction,
    handleBarcodeScanSubmit,
    openQuickCreate,
    openProductQuickCreateFromBarcode,
    handleProductCreateSuccess,
    closeProductCreateModal,
    closeQuickCreate,
    handleQuickCreateSubmit,
    applyTaxPreset,
    applyCustomTaxRate,
    applyDiscount,
    handleFileUpload,
    handleRemoveAttachment,
    handleSaveDraft,
    handleResetDraft,
    handleConfirmInvoice,
    handleNewPurchaseOrder,
    setCreatedPurchase,
  };
}
